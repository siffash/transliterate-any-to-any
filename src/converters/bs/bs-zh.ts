import { Text } from "types";

export const bsZh = async (text: Text) => {
  const { convertText } = await import("helpers/convertText");
  const { bsIpaRules } = await import("data/bs/bs-ipa.rules");
  const { ipaZhOvaRules } = await import("data/ipa/ipa-zh_ova.rules");
  const { ipaZhRules } = await import("data/ipa/ipa-zh.rules");
  const { ipaZhLjeRules } = await import("data/ipa/ipa-zh_lje.rules");

  return convertText(text, bsIpaRules + ipaZhOvaRules + ipaZhLjeRules + ipaZhRules);
};
